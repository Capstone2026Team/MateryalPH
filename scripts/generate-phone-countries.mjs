import { readFileSync, writeFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'

const root = new URL('../', import.meta.url)
const source = JSON.parse(readFileSync(new URL('packages/shared-data/phone-countries.json', root), 'utf8'))
const names = new Intl.DisplayNames(['en'], { type: 'region' })
const countries = source.countries.map(({ region, callingCode, mainCountry }) => ({ region, callingCode, mainCountry, name: names.of(region) }))
  .sort((a, b) => a.region === 'PH' ? -1 : b.region === 'PH' ? 1 : a.name.localeCompare(b.name, 'en'))
const header = '// Generated by scripts/generate-phone-countries.mjs; do not edit.\n'
const outputs = {
  'packages/web-ui/src/phone-countries.ts': `${header}export const phoneCountries = ${JSON.stringify(countries, null, 2)} as const\n`,
  'apps/buyer-mobile/lib/widgets/phone_countries.dart': `${header}const phoneCountries = <({String region, String callingCode, bool mainCountry, String name})>[\n${countries.map(c => `  (region: ${JSON.stringify(c.region)}, callingCode: ${JSON.stringify(c.callingCode)}, mainCountry: ${c.mainCountry}, name: ${JSON.stringify(c.name)}),`).join('\n')}\n];\n`,
}
for (const [path, content] of Object.entries(outputs)) {
  const url = new URL(path, root)
  let formatted = content
  if (path.endsWith('.dart')) {
    const result = spawnSync(process.platform === 'win32' ? 'cmd.exe' : 'dart',
      process.platform === 'win32' ? ['/d', '/c', 'dart', 'format', '--output=show', '--summary=none'] : ['format', '--output=show', '--summary=none'],
      { input: content, encoding: 'utf8', windowsHide: true })
    if (result.error || result.status !== 0) throw new Error('Dart SDK is required to format generated phone countries.')
    formatted = result.stdout.replaceAll('\r\n', '\n')
  }
  if (process.argv.includes('--check')) {
    if (readFileSync(url, 'utf8').replaceAll('\r\n', '\n') !== formatted) throw new Error(`Regenerate ${path}`)
  } else writeFileSync(url, formatted)
}
console.log(`Phone country outputs ${process.argv.includes('--check') ? 'checked' : 'generated'} (${countries.length} regions).`)
